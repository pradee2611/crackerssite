const escapeRe = (k: string) => k.replace(/[.*+?^$(){}|\[\]]/g, "\\$&");

const WORD_RES = (Object.keys(WORDS) as Exclude<Lang, "en">[]).reduce(
  (acc, lang) => {
    acc[lang] = Object.keys(WORDS[lang])
      .sort((a, b) => b.length - a.length)
      .map((k): [RegExp, string] => [new RegExp("(?<![A-Za-z])" + escapeRe(k) + "(?![A-Za-z])", "g"), WORDS[lang][k]]);
    return acc;
  },
  {} as Record<Exclude<Lang, "en">, [RegExp, string][]>
);

/** Translate a product name, variant or combo item. Numbers and unknown words stay as they are. */
export function translateName(lang: Lang, text: string): string {
  if (lang === "en" || !text) return text;
  return WORD_RES[lang].reduce((s, [re, to]) => s.replace(re, to), text);
}
